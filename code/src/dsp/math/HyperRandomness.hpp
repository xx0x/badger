#pragma once

#include <cstdint>

namespace badger
{
/**
 * @brief Lightweight deterministic PRNG used by the Badger.
 * @details
 * This is used to prevent the same random numbers generated by rand() every time.
 * Super lightweight, no dependencies, just need to seed it and add some entropy from time to time.
 * @author Vaclav Mach
 * @date 2026-06-20
 */
class HyperRandomness
{
public:
    /**
     * @brief Sets the internal PRNG state.
     * @param seed Initial seed value.
     */
    static void Seed(uint32_t seed);

    /**
     * @brief Mixes additional entropy into the current state.
     * @param entropy Entropy value to fold into the generator state.
     */
    static void AddEntropy(uint32_t entropy);

    /**
     * @brief Generates a random 32-bit unsigned integer.
     * @return A random 32-bit unsigned integer.
     */
    static uint32_t NextU32();

    /**
     * @brief Generates a random 16-bit unsigned integer.
     * @return A random 16-bit unsigned integer.
     */
    static uint16_t NextU16();

    /**
     * @brief Generates a random float in the range[0.0f, 1.0f].
     * @return A random float in the range[0.0f, 1.0f]
     */
    static float NextFloat();

    /**
     * @brief Generates a random signed integer in [min_inclusive, max_exclusive).
     * @param min_inclusive Minimum value (inclusive).
     * @param max_exclusive Maximum value (exclusive).
     * @return A random signed integer in the specified range.
     */
    static int32_t NextRange(int32_t min_inclusive, int32_t max_exclusive);

private:
    static uint32_t Scramble(uint32_t value);
    static inline uint32_t state_ = 0x6D2B79F5u;
    static inline bool seeded_ = false;
};
} // namespace badger
