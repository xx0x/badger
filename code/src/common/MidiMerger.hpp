#pragma once

#include <array>
#include <cstddef>
#include <cstdint>
#include <functional>

#include "utils/EnumTools.hpp"

namespace badger
{

/**
 * @brief Merges several MIDI byte streams into one output without breaking messages apart.
 * @details
 * Every input stream is reassembled into complete messages before anything is written out, so a
 * message from one input can never end up in the middle of another input's message. Running status
 * on the inputs is expanded: every message goes out with its own status byte, so the output stays
 * readable for a device plugged in mid-stream, whatever the inputs did before.
 *
 * - Real-time bytes go straight through, MIDI allows them anywhere, even inside other messages.
 * - A SysEx is streamed through as it arrives. While it is in progress, complete messages from the
 *   other inputs are held back and sent right after it ends (if they fit into the hold buffer).
 *   A second SysEx starting meanwhile on another input is dropped, two can't be merged.
 * - A SysEx that stops arriving halfway is closed after kSysexTimeoutMs, so it doesn't block the
 *   other inputs forever.
 * - Every write to the output is all or nothing, so a full output drops whole messages, never
 *   single bytes out of them.
 *
 * @author Vaclav Mach
 * @date 2026-10-17
 */
class MidiMerger
{
public:
    /**
     * @brief The streams being merged.
     */
    enum class Input : uint8_t
    {
        LOCAL, ///< Messages generated by the Badger itself
        TRS,   ///< TRS MIDI in passthrough
        USB,   ///< USB MIDI in passthrough
        COUNT
    };

    /**
     * @brief Writes one unit (a whole message, a real-time byte, or a piece of a SysEx) to the output.
     * @return False if it didn't fit, in which case nothing at all may have been written.
     */
    using Sink = std::function<bool(const uint8_t *data, size_t length)>;

    /**
     * @brief How long a SysEx may pause before it is considered abandoned, in milliseconds.
     */
    static constexpr uint32_t kSysexTimeoutMs = 500;

    /**
     * @brief Sets where the merged stream goes.
     */
    void SetSink(Sink sink);

    /**
     * @brief Forgets all partial messages and held back data, e.g. after the output was cleared.
     */
    void Reset();

    /**
     * @brief Feeds one byte of an input's stream.
     */
    void Write(Input input, uint8_t byte);

    /**
     * @brief Feeds several bytes of an input's stream.
     */
    void Write(Input input, const uint8_t *data, size_t length);

    /**
     * @brief Keeps track of time for the SysEx timeout. Call it periodically.
     * @param now_ms Current time in milliseconds.
     */
    void Process(uint32_t now_ms);

private:
    /**
     * @brief Reassembly state of one input stream.
     */
    struct Assembler
    {
        uint8_t running_status = 0;
        uint8_t status = 0;
        uint8_t expected_data_bytes = 0;
        uint8_t received_data_bytes = 0;
        std::array<uint8_t, 2> data = {0, 0};
        bool in_sysex = false;
        bool dropping_sysex = false; ///< This input's current SysEx can't be passed through, its bytes are discarded
    };

    static constexpr Input kNoInput = Input::COUNT;
    static constexpr uint8_t kSysexStart = 0xF0;
    static constexpr uint8_t kSysexEnd = 0xF7;
    static constexpr uint8_t kFirstRealTime = 0xF8;

    /**
     * @brief Room for messages held back during another input's SysEx, enough for a couple dozen of them.
     */
    static constexpr size_t kHoldBufferSize = 64;

    void HandleStatus(Input input, Assembler &assembler, uint8_t status);
    void HandleData(Input input, Assembler &assembler, uint8_t byte);
    void CompleteMessage(Input input, Assembler &assembler);
    void PassSysex(Assembler &assembler, uint8_t byte);
    void EndSysex(Assembler &assembler);
    void ReleaseSysex();
    void Hold(const uint8_t *data, size_t length);
    void FlushHeld();
    bool Emit(const uint8_t *data, size_t length);

    Sink sink_;
    EnumArray<Input, Assembler> assemblers_{};

    // Input whose SysEx is currently going out, kNoInput if none
    Input sysex_owner_ = kNoInput;
    uint32_t sysex_last_activity_ms_ = 0;
    uint32_t now_ms_ = 0;

    std::array<uint8_t, kHoldBufferSize> held_{};
    size_t held_length_ = 0;
};

} // namespace badger
